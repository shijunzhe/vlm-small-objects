#!/usr/bin/env python3
"""Rank correlation, over the ten settings of the rule table, between the rule's recall gain and the median S
of the whole-image call (tokens per target side, as stored with every rule record).
Run from experiments/:  python3 ../paper_v3/scripts/gain_vs_sw.py
Writes ../paper_v3/generated/macros_gain.tex and gain_vs_sw.json."""
import glob, json, statistics
from pathlib import Path
from scipy.stats import spearmanr
G = Path(__file__).resolve().parent.parent / 'generated'
tab = json.load(open(G / 'tab1.json'))
rows = {}
for f in sorted(glob.glob('results_cs/*/CS_*_run0.jsonl')):
    ds = 'redp' if '/redp/' in f else 'fpc'
    v = f.split('CS_')[1].split('_run')[0]
    sw = {}
    for line in open(f):
        r = json.loads(line); m = r.get('meta', r)
        if m.get('did') is not None and m.get('Sw') is not None:
            sw[m['did']] = m['Sw']
    key = f'{ds}|{v}'
    if key in tab and sw:
        rows[key] = {'Sw_median': statistics.median(sw.values()), 'dRec': tab[key]['dRec'][0], 'recW': tab[key]['recW']}
keys = sorted(rows)
rho_s, p_s = spearmanr([rows[k]['Sw_median'] for k in keys], [rows[k]['dRec'] for k in keys])
rho_w, p_w = spearmanr([rows[k]['recW'] for k in keys], [rows[k]['dRec'] for k in keys])
json.dump({'rows': rows, 'rho_Sw': rho_s, 'p_Sw': p_s, 'rho_recW': rho_w, 'p_recW': p_w}, open(G / 'gain_vs_sw.json', 'w'), indent=1, sort_keys=True)
def f(x): return f'{x:+.2f}'.replace('-', '$-$')
with open(G / 'macros_gain.tex', 'w') as out:
    out.write('% generated by scripts/gain_vs_sw.py; do not edit\n')
    out.write('\\newcommand{\\CgainN}{%d}\n' % len(keys))
    out.write('\\newcommand{\\CgainRhoSw}{%s}\n' % f(rho_s))
    out.write('\\newcommand{\\CgainPSw}{%.2f}\n' % p_s)
    out.write('\\newcommand{\\CgainRhoRecW}{%s}\n' % f(rho_w))
    out.write('\\newcommand{\\CgainPRecW}{%.2f}\n' % p_w)
print(len(keys), rho_s, p_s, rho_w, p_w)
