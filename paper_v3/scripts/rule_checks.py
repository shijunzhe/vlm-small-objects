#!/usr/bin/env python3
"""Two checks on the stored rule records, without model calls.
(1) Cost fixed in advance: for every drawing and model, the number of views sent equals the planned number,
    and every view of a drawing is billed the same number of input tokens.
(2) Fewer images need splitting: on the shared Gemini grid, the share of LegendSpot test drawings whose
    whole-image S already reaches each model's S90 (Gemini 3.8 and Gemini 4, vspec).
Run from experiments/:  python3 ../paper_v3/scripts/rule_checks.py
Writes ../paper_v3/generated/macros_rulechecks.tex and rule_checks.json."""
import collections, glob, json, sys
from pathlib import Path
sys.path.insert(0, '.')
import cs_rule as CR, mech as M
G = Path(__file__).resolve().parent.parent / 'generated'
pairs = mismatch = 0; spread = 0.0
for f in sorted(glob.glob('results_cs/*/CS_*_run0.jsonl')):
    ds = 'fpc' if '/fpc/' in f else 'redp'; v = f.split('CS_')[1].split('_run')[0]
    calls = collections.Counter(); bill = collections.defaultdict(list)
    for line in open(f):
        r = json.loads(line); m = r.get('meta', r); calls[m['did']] += 1
        if r.get('status') in ('success', 'parse_error'): bill[m['did']].append((r.get('usage') or {}).get('input_tokens', 0))
    base = Path('../data/fpc/sheets/annotations') if ds == 'fpc' else M.BENCH / 'annotations'
    for did, c in calls.items():
        ann = json.loads((base / f'{did}.json').read_text()); pairs += 1
        mismatch += CR.plan(v, ann)['n_views'] != c
        b = bill[did]
        if b: spread = max(spread, (max(b) - min(b)) / max(1, min(b)))
s90 = {'gem38': json.load(open('vspec/frozen_s90.json'))['gem38']['S_ref'], 'gem4': json.load(open('vspec/frozen_s90_gem4.json'))['S90']}
sw = {}
for line in open('results_cs/redp/CS_gem38_run0.jsonl'):
    r = json.loads(line); m = r.get('meta', r); sw[m['did']] = m['Sw']
reach = {k: sum(x >= t for x in sw.values()) for k, t in s90.items()}
json.dump({'pairs': pairs, 'mismatch': mismatch, 'max_spread': spread, 'S90': s90, 'reach': reach, 'n_drawings': len(sw)},
          open(G / 'rule_checks.json', 'w'), indent=1, sort_keys=True)
with open(G / 'macros_rulechecks.tex', 'w') as out:
    out.write('% generated by scripts/rule_checks.py; do not edit\n')
    out.write('\\newcommand{\\CcostPairs}{%d}\n\\newcommand{\\CcostMismatch}{%d}\n' % (pairs, mismatch))
    out.write('\\newcommand{\\CreachN}{%d}\n\\newcommand{\\CreachGemThreeEight}{%d}\n\\newcommand{\\CreachGemFour}{%d}\n' % (len(sw), reach['gem38'], reach['gem4']))
print(pairs, mismatch, spread, reach, len(sw))
