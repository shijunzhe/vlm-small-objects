"""Optional reading of points written with x/y keys (paper v2, Appendix E).

The registered reader keeps a point only if it carries the requested numeric cx/cy keys. Gemini 3.8 sometimes
writes {"x": .., "y": ..} or {"cx": .., "y": ..} instead. Run ../xy_reading.sh to rescore every experiment with
those points read as well (POINT_XY=1, in a temporary copy); it calls this script, which writes
../paper/generated/macros_xy.tex with
  * \\xy<name> for every macro of macros_x.tex whose value changes under that reading, and
  * counts of Gemini 3.8 points by key format in the shipped answers.
Usage: python3 xy_macros.py <root of the rescored copy>
"""
import json, re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
OTHER = Path(sys.argv[1]).resolve()


def macros(p):
    return {m.group(1): m.group(2) for m in re.finditer(r'\\newcommand\{\\(\w+)\}\{(.*)\}\s*$', p.read_text(), re.M)}


def num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def key_counts(files):
    """(points with numeric cx/cy, points with x/y keys instead) over the parsed shapes of the given answer files."""
    ok = xy = 0
    for f in files:
        for line in open(f):
            r = json.loads(line)
            for q in r.get('shapes') or []:
                if not isinstance(q, dict):
                    continue
                if num(q.get('cx')) is not None and num(q.get('cy')) is not None:
                    ok += 1
                elif num(q.get('cx', q.get('x'))) is not None and num(q.get('cy', q.get('y'))) is not None:
                    xy += 1
    return ok, xy


reg, alt = macros(ROOT / 'paper/generated/macros_x.tex'), macros(OTHER / 'paper/generated/macros_x.tex')
out = ['% generated by experiments/xy_macros.py (via xy_reading.sh): values under the optional x/y reading']
for k in sorted(reg):
    if alt.get(k) is not None and alt[k] != reg[k]:
        out.append(f'\\newcommand{{\\xy{k}}}{{{alt[k]}}}')
E = ROOT / 'experiments'
groups = {'Fsc': sorted((ROOT / 'data/fsc147/results').glob('gem38_?_obj.jsonl')),
          'Syn': sorted((E / 'syn/results').glob('gem38*_run0.jsonl')),
          'Battery': [E / 'syn_assume/results/gem38.jsonl'],
          'Agent': [E / 'results_x/agent/gem38_run0.jsonl']}
for g, files in groups.items():
    ok, xy = key_counts(files)
    out.append(f'\\newcommand{{\\xyKeys{g}}}{{{xy:,}}}'.replace(',', '{,}'))
    out.append(f'\\newcommand{{\\xyKeysPct{g}}}{{{100 * xy / (ok + xy):.0f}}}')
(ROOT / 'paper/generated/macros_xy.tex').write_text('\n'.join(out) + '\n')
print(f'{len(out) - 1} macros written to paper/generated/macros_xy.tex')
